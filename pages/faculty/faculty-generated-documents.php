            <?php if (isset($manifest['files']['sdg_continuation'])): ?><a class="frr-btn" href="<?= facultyRecordEscape(SITE_URL . 'pages/shared/download-earist-document.php?' . http_build_query(['id' => (int) $row['generated_document_id'], 'file' => 'sdg_continuation'])) ?>">Download QSF SDG companion</a><?php endif; ?>
          </td>
        </tr>
      <?php endforeach; ?>
      </tbody></table></div>
      <?php
        $lastPage = max(1, (int) ceil($history['total'] / $history['page_size']));
        $total = (int) $history['total'];
        $pageSize = (int) $history['page_size'];

        // Build page range with ellipsis
        function buildPageRange(int $currentPage, int $lastPage, int $window = 2): array {
            $range = [];
            if ($lastPage <= 7) {
                for ($i = 1; $i <= $lastPage; $i++) $range[] = $i;
            } else {
                $range[] = 1;
                $start = max(2, $currentPage - $window);
                $end = min($lastPage - 1, $currentPage + $window);
                if ($start > 2) $range[] = '...';
                for ($i = $start; $i <= $end; $i++) $range[] = $i;
                if ($end < $lastPage - 1) $range[] = '...';
                $range[] = $lastPage;
            }
            return $range;
        }

        $pageRange = buildPageRange($page, $lastPage);
        $baseUrl = facultyRecordEscape(SITE_URL . 'pages/faculty/faculty-generated-documents.php');
